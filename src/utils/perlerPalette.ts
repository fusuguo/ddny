/**
 * 从色号提取字母前缀（如 'G17' → 'G'，'ZG1' → 'ZG'）
 */
export function getLetterPrefix(code: string): string {
  return code.replace(/[0-9]+$/, '');
}

/**
 * 从色号提取数字后缀（如 'G17' → 17，'ZG1' → 1）
 */
export function getNumberSuffix(code: string): number {
  const match = code.match(/[0-9]+$/);
  return match ? parseInt(match[0], 10) : 0;
}

/**
 * 获取所有字母前缀（去重，保持色板中的顺序）
 */
export function getLetters(): string[] {
  const seen = new Set<string>();
  const result: string[] = [];
  for (const entry of PERLER_PALETTE) {
    const prefix = getLetterPrefix(entry.code);
    if (!seen.has(prefix)) {
      seen.add(prefix);
      result.push(prefix);
    }
  }
  return result;
}

/**
 * 获取指定字母前缀下的所有数字编号（升序）
 */
export function getNumbersForLetter(letter: string): number[] {
  return PERLER_PALETTE.filter((entry) => getLetterPrefix(entry.code) === letter)
    .map((entry) => getNumberSuffix(entry.code))
    .sort((a, b) => a - b);
}

/**
 * 根据色号查找对应颜色
 */
export function findByCode(code: string): PerlerColor | undefined {
  return PERLER_PALETTE.find((entry) => entry.code === code);
}
